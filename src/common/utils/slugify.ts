/** Texto sem acento, minúsculo, com hífens no lugar do que não é letra nem número, até 60 caracteres (nome de arquivo). */
export function slugify(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}
